// Generates an idempotent, failure-tolerant SQL script that brings any
// PostgreSQL database up to prisma/schema.prisma without ever dropping data:
//
//   * CREATE TABLE / CREATE INDEX gain IF NOT EXISTS
//   * every column is re-declared with ADD COLUMN IF NOT EXISTS (a required
//     column that can't be added to a populated table falls back to nullable)
//   * foreign keys are added only when missing
//   * columns that exist only in the database and are NOT NULL without a
//     default get their NOT NULL dropped, otherwise Prisma inserts fail (P2011)
//
// Each statement runs in its own exception block, so one failure never stops
// the rest. Output: prisma/schema-repair.sql (for `prisma db execute`) and
// src/lib/schema-repair.generated.ts (for the runtime self-heal).
//
// Usage: node scripts/gen-schema-repair.mjs [--check]
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SQL_OUT = path.join(root, "prisma/schema-repair.sql");
const TS_OUT = path.join(root, "src/lib/schema-repair.generated.ts");

function schemaSql() {
  const result = spawnSync(
    "npx",
    ["prisma", "migrate", "diff", "--from-empty", "--to-schema-datamodel", "prisma/schema.prisma", "--script"],
    { cwd: root, encoding: "utf8" },
  );
  if (result.status !== 0) {
    throw new Error(`prisma migrate diff failed:\n${result.stderr}`);
  }
  return result.stdout;
}

function splitStatements(sql) {
  return sql
    .split("\n")
    .filter((line) => !line.trim().startsWith("--"))
    .join("\n")
    .split(/;\s*\n/)
    .map((s) => s.trim().replace(/;$/, ""))
    .filter(Boolean);
}

function guarded(sql, fallback) {
  const inner = fallback
    ? `BEGIN EXECUTE $q$${sql}$q$; EXCEPTION WHEN OTHERS THEN BEGIN EXECUTE $q$${fallback}$q$; EXCEPTION WHEN OTHERS THEN RAISE NOTICE 'schema-repair skipped: %', SQLERRM; END; END;`
    : `EXECUTE $q$${sql}$q$; EXCEPTION WHEN OTHERS THEN RAISE NOTICE 'schema-repair skipped: %', SQLERRM;`;
  return `DO $do$ BEGIN ${inner} END $do$`;
}

export function buildRepair(sql) {
  const statements = [];
  const tables = {};

  for (const stmt of splitStatements(sql)) {
    const createTable = stmt.match(/^CREATE TABLE "([^"]+)" \(([\s\S]*)\)$/);
    if (createTable) {
      const [, table, body] = createTable;
      statements.push(guarded(stmt.replace(/^CREATE TABLE/, "CREATE TABLE IF NOT EXISTS")));
      const columns = body
        .split(/,\n/)
        .map((line) => line.trim())
        .filter((line) => line.startsWith('"'));
      tables[table] = columns.map((line) => line.match(/^"([^"]+)"/)[1]);
      for (const def of columns) {
        const add = `ALTER TABLE "${table}" ADD COLUMN IF NOT EXISTS ${def}`;
        const needsFallback = /NOT NULL/.test(def) && !/DEFAULT/.test(def);
        statements.push(guarded(add, needsFallback ? add.replace(" NOT NULL", "") : undefined));
      }
      continue;
    }
    if (/^CREATE (UNIQUE )?INDEX /.test(stmt)) {
      statements.push(guarded(stmt.replace(/^CREATE (UNIQUE )?INDEX /, (m) => `${m}IF NOT EXISTS `)));
      continue;
    }
    // Postgres has no ADD CONSTRAINT IF NOT EXISTS; a duplicate is simply skipped.
    statements.push(guarded(stmt));
  }

  const expected = Object.entries(tables)
    .flatMap(([table, cols]) => cols.map((col) => `${table}.${col}`))
    .map((key) => `'${key}'`)
    .join(",");
  const tableList = Object.keys(tables)
    .map((t) => `'${t}'`)
    .join(",");
  statements.push(
    `DO $do$ DECLARE r record; BEGIN FOR r IN SELECT table_name, column_name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name IN (${tableList}) AND is_nullable = 'NO' AND column_default IS NULL AND (table_name || '.' || column_name) <> ALL (ARRAY[${expected}]) LOOP BEGIN EXECUTE format('ALTER TABLE %I ALTER COLUMN %I DROP NOT NULL', r.table_name, r.column_name); EXCEPTION WHEN OTHERS THEN RAISE NOTICE 'schema-repair skipped: %', SQLERRM; END; END LOOP; END $do$`,
  );

  return { statements, tables };
}

function render({ statements, tables }) {
  const header = "-- Generated by scripts/gen-schema-repair.mjs from prisma/schema.prisma. Do not edit.\n";
  const sqlFile = header + statements.map((s) => `${s};\n`).join("");
  const tsFile =
    "// Generated by scripts/gen-schema-repair.mjs from prisma/schema.prisma. Do not edit.\n\n" +
    `export const SCHEMA_TABLES: Record<string, readonly string[]> = ${JSON.stringify(tables, null, 2)};\n\n` +
    `export const SCHEMA_REPAIR_STATEMENTS: readonly string[] = ${JSON.stringify(statements, null, 2)};\n`;
  return { sqlFile, tsFile };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const { sqlFile, tsFile } = render(buildRepair(schemaSql()));
  if (process.argv.includes("--check")) {
    const stale = [
      [SQL_OUT, sqlFile],
      [TS_OUT, tsFile],
    ].filter(([file, content]) => {
      try {
        return readFileSync(file, "utf8") !== content;
      } catch {
        return true;
      }
    });
    if (stale.length) {
      console.error("[schema-repair] stale — run `node scripts/gen-schema-repair.mjs`");
      process.exit(1);
    }
    console.log("[schema-repair] up to date");
  } else {
    writeFileSync(SQL_OUT, sqlFile);
    writeFileSync(TS_OUT, tsFile);
    console.log(`[schema-repair] wrote ${path.relative(root, SQL_OUT)} and ${path.relative(root, TS_OUT)}`);
  }
}
