function applyPhraseReps(s, locale) {
  const reps = FR_PHRASES[locale] || [];
  for (const [re, rep] of reps) s = s.replace(re, rep);
  return s;
}

function translateFr(fr, locale) {
  // Apply full-sentence phrase translations first on pristine French
  let s = applyPhraseReps(fr, locale);
  if (locale === "de") s = fr2de(s);
  else if (locale === "es") s = fr2es(s);
  else if (locale === "it")
    s = fr2es(s)
      .replace(/ción/g, "zione")
      .replace(/Buscar/g, "Cerca")
      .replace(/Guardar/g, "Salva")
      .replace(/Proveedores/g, "Fornitori")
      .replace(/proveedores/g, "fornitori")
      .replace(/Productos/g, "Prodotti")
      .replace(/Configuración/g, "Impostazioni")
      .replace(/Carrito/g, "Carrello");
  else if (locale === "pt")
    s = fr2es(s)
      .replace(/ción/g, "ção")
      .replace(/Buscar/g, "Pesquisar")
      .replace(/Configuración/g, "Definições")
      .replace(/Contraseña/g, "Palavra-passe")
      .replace(/Carrito/g, "Carrinho");
  else if (locale === "nl")
    s = fr2de(s)
      .replace(/Lieferanten/g, "Leveranciers")
      .replace(/Produkte/g, "Producten")
      .replace(/Einstellungen/g, "Instellingen")
      .replace(/Datenschutz/g, "Privacy")
      .replace(/Warenkorb/g, "Winkelwagen")
      .replace(/Preise/g, "Prijzen");
  else if (locale === "ar") s = fr2ar(s);
  else if (locale === "tr") s = fr2tr(s);
  else if (locale === "zh") s = fr2zh(s);
  else if (locale === "ja") s = fr2ja(s);
  else if (locale === "ko") s = fr2ko(s);
  else if (locale === "hi") s = fr2hi(s);
  return s;
}

// Build maps: English key -> translated value (via French bridge from complete fr.json)
